def _extract_target_message_from_base_prompt(base_prompt: str) -> str:
    """base_prompt から『対象メッセージ: ...』のテキストを抽出する。見つからなければ base_prompt を返す。"""
    raw = str(base_prompt or "").strip()
    match = re.search(r"対象メッセージ:\s*([^\n]+)", raw)
    if match:
        return match.group(1).strip()
    return raw


