def build_playful_say_request_instruction(
    target_word: str,
    count: int | None = None,
    bot_identity: Any = None,
) -> list[str]:
    """言葉遊び・セリフ指定のリクエスト（「〇〇って10回言って」等）に対する強力な実行指示を生成する。"""
    clean_word = str(target_word or "").strip()
    if not clean_word:
        return []

    lines = [
        "",
        "【ユーザーのリクエスト・セリフ指定の実行指示（最優先）】",
    ]
    if count and count > 1:
        sample_repeat = "、".join([clean_word] * min(count, 5))
        if count > 5:
            sample_repeat += f"…！（これで{count}回）"
        lines += [
            f"※ ユーザーは『{clean_word}』と{count}回言うことを要求（言葉遊びのリクエスト）しています。",
            f"※ 時間帯（深夜等）や『意味が分からない』『急に何』等の理屈を言い訳にして言うのを拒絶・回避することは【固く禁止】します。",
            f"※ あなたのキャラクター口調や性格（戸惑い、照れ、ブツブツ不満を言いながら等）を保ったまま、必ずセリフの中で実際に『{clean_word}』という言葉を繰り返して言ってあげてください。",
            f"※ 出力例: 『…な、なんでそんなこと言わせるんですか…！ …{sample_repeat}…！ も、もう{count}回言いましたよ…！ これで満足ですか…？』のように、キャラクターらしく戸惑いながらも、指定された単語を実際に口にすること。",
        ]
    else:
        lines += [
            f"※ ユーザーは『{clean_word}』と言ってほしいと要求（セリフ指定・言葉遊び）しています。",
            f"※ 時間帯（深夜等）や照れ・理屈を言い訳にして言うのを拒絶・回避することは【固く禁止】します。",
            f"※ あなたのキャラクター口調や性格（照れ、ツンデレ、戸惑い、ブツブツ言いながら等）を保ったまま、必ずセリフの中で実際に『{clean_word}』という言葉を言って要望を叶えてあげてください。",
            f"※ 出力例: 『…っ、急に何言わせようとしてるんですか…！ …{clean_word}…ですよ…！ ば、バカ…二度と言いませんからね…！』のように、キャラクターの照れや戸惑いの台詞を添えつつ、指定された言葉を実際に口にすること。",
        ]

    lines.append("※ 会話の返答だけで言葉を言わずに済ませる（メタ会話で逃げる）ことは絶対にせず、必ず指定された言葉をセリフに含めてください。")
    return lines


